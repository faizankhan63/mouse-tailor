# Words that differ between the kernel's device names and LogiOps's, ignored when matching them.
_GENERIC_WORDS = {"logitech", "wireless", "mouse", "multi-device", "trackball", "keyboard", "receiver"}


def control_name(cid):
    return CONTROLS.get(cid, (f"Button {cid:#x}", None))[0]


def control_default(cid):
    return CONTROLS.get(cid, (None, None))[1]


def empty_button():
    return {"mode": "default", "keys": [], "gestures": {}}


def new_device(controls):
    return {"controls": controls, "buttons": {}}


def has_scroll_wheel(name):
    return "keyboard" not in name.lower() and "keys" not in name.lower()


def scroll_speed(device):
    return device.get("scroll_speed", 1)


def scroll_inverted(device):
    return device.get("scroll_invert", False)


def visible_controls(device):
    return [(cid, gestures) for cid, gestures in device["controls"] if cid not in HIDDEN_CONTROLS]


def get_button(device, cid):
    return device["buttons"].setdefault(hex(cid), empty_button())


def short_name(name):
    return name.strip()


def load_settings():
    saved = {}
    for path in (SETTINGS_FILE, LEGACY_SETTINGS_FILE):
        try:
            saved = json.loads(path.read_text())
            break
        except (OSError, ValueError):
            continue
    if "buttons" in saved and "devices" not in saved:
        # Settings from before multi-device support were for the M720.
        name = "M720 Triathlon Multi-Device Mouse"
        saved = {"devices": {name: {"controls": KNOWN_DEVICES[name], "buttons": saved["buttons"]}}}
    saved.setdefault("devices", {})
    # Removed devices whose scroll wheel still has to be handed back to the system.
    saved.setdefault("scroll_restore", [])
    return saved


def save_settings(settings):
    SETTINGS_FILE.parent.mkdir(parents=True, exist_ok=True)
    SETTINGS_FILE.write_text(json.dumps(settings, indent=2))


def key_label(name):
    if name in KEY_LABELS:
        return KEY_LABELS[name]
    return name.split("_", 1)[-1].replace("_", " ").title()


def describe_keys(keys):
    """A preset's name when the keys match one, otherwise the combo, e.g. "Ctrl + Shift + T"."""
    if not keys:
        return None
    for _, label, preset in PRESETS:
        if preset == keys:
            return label
    return " + ".join(key_label(k) for k in keys)


def describe_button(cid, button):
    mode = button["mode"]
    if mode == "disabled":
        return "Disabled"
    if mode == "shortcut" and button["keys"]:
        return describe_keys(button["keys"])
    if mode == "gestures":
        parts = [f"{short}: {describe_keys(button['gestures'][d]['keys'])}"
                 for d, _, short in DIRECTIONS
                 if button["gestures"].get(d, {}).get("keys")]
        return " · ".join(parts) or "Gestures (nothing assigned)"
    default = control_default(cid)
    return f"Default ({default})" if default else "Default"


def describe_speed(speed):
    return "Normal" if speed == 1 else f"{speed}× faster"


def changed_count(device):
    return sum(1 for cid, _ in visible_controls(device) if _button_entry(get_button(device, cid)))


def describe_device(device):
    changed = changed_count(device)
    parts = [f"{changed} button{'s' if changed != 1 else ''} changed"] if changed else []
    if scroll_speed(device) != 1:
        parts.append(f"scrolling {scroll_speed(device)}× faster")
    if scroll_inverted(device):
        parts.append("reversed scrolling")
    return ", ".join(parts).capitalize() or "Default settings"


def _words(text):
    return set(text.lower().split()) - _GENERIC_WORDS


def connected_devices():
    """Names the kernel gives to input devices, from /proc/bus/input/devices."""
    try:
        text = Path("/proc/bus/input/devices").read_text()
    except OSError:
        return []
    return re.findall(r'^N: Name="(.*)"$', text, re.MULTILINE)


def is_connected(name, connected):
    words = _words(name)
    return bool(words) and any(words <= _words(kernel_name) for kernel_name in connected)


def parse_detection(output):
    """Devices and their remappable controls from `logid -v` output: {name: [[cid, gestures], ...]}."""
    names, devices, current = {}, {}, None
    for line in output.splitlines():
        found = re.search(r"Device found: (.*) on (\S+)$", line)
        if found:
            names[found.group(2)] = found.group(1)
            continue
        header = re.search(r"\] (\S+) remappable buttons:", line)
        if header:
            current = names.get(header.group(1))
            if current is not None:
                devices[current] = []
            continue
        row = re.match(r"\[DEBUG\] (0x[0-9a-fA-F]+)\s*\|([^|]*)\|([^|]*)\|([^|]*)\|(.*)$", line)
        if row and current is not None:
            reprogrammable, gestures = "YES" in row.group(2), "YES" in row.group(5)
            if reprogrammable:
                devices[current].append([int(row.group(1), 16), gestures])
        elif not line.startswith("[DEBUG] CID"):
            current = None
    return devices


_header_names = None


def evdev_key_name(code):
    """Name such as "KEY_A" for an evdev key code, or None if unknown."""
    global _header_names
    try:
        from evdev import ecodes
        name = ecodes.KEY.get(code) or ecodes.BTN.get(code)
    except ImportError:
        if _header_names is None:
            _header_names = {}
            header = Path("/usr/include/linux/input-event-codes.h")
            if header.exists():
                for m in re.finditer(r"#define\s+(KEY_\w+)\s+(0x[0-9a-fA-F]+|\d+)", header.read_text()):
                    _header_names.setdefault(int(m.group(2), 0), m.group(1))
        name = _header_names.get(code)
    if isinstance(name, (list, tuple)):
        name = next((n for n in name if "INTERESTING" not in n), name[0])
    return name


def _quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _keypress(keys):
    return "{ type: \"Keypress\"; keys: [" + ", ".join(_quote(k) for k in keys) + "]; }"


def _button_entry(button):
    """libconfig lines for a button's action, or None when it keeps its default."""
    mode = button["mode"]
    if mode == "disabled":
        return ['action = { type: "None"; };']
    if mode == "shortcut":
        return [f"action = {_keypress(button['keys'])};"] if button["keys"] else None
    if mode != "gestures":
        return None

    gestures = []
    for direction, label, _ in DIRECTIONS:
        gesture = button["gestures"].get(direction, {})
        keys = gesture.get("keys")
        if keys:
            if direction != "None" and gesture.get("repeat"):
                mode_text = f'mode: "OnInterval"; interval: {REPEAT_INTERVAL};'
            else:
                mode_text = 'mode: "OnRelease";'
            gestures.append(f'        // {label}\n'
                            f'        {{ direction: "{direction}"; {mode_text} action = {_keypress(keys)}; }}')
        elif direction == "None":
            # Without this, a tap with nothing assigned would fall through to the old behaviour.
            gestures.append('        // Tap: nothing\n        { direction: "None"; mode: "NoPress"; }')
    return ['action =', '{', '    type: "Gestures";', '    gestures: (',
            *",\n".join(gestures).split("\n"), '    );', '};']


def _scroll_entry(speed, invert=False):
    """libconfig lines for the scroll wheel at a speed multiplier (1 = normal), optionally reversed."""
    invert_text = "true" if invert else "false"
    if speed == 1:
        # Hand the wheel back to the system in hi-res mode, the way the kernel sets it up.
        return [f"// Scroll wheel: normal speed{', reversed' if invert else ''}",
                f"hiresscroll: {{ hires: true; invert: {invert_text}; target: false; }};"]
    # logid takes over the wheel and sends `speed` steps per click. Low-res mode and the
    # REL_WHEEL axis work around LogiOps 0.3 bugs with the hi-res axis (issues #370, #427);
    # multipliers must be written as decimals for the same reason.
    return [f"// Scroll wheel: {speed}x faster{', reversed' if invert else ''}",
            "hiresscroll:",
            "{",
            "    hires: false;",
            f"    invert: {invert_text};",
            "    target: true;",
            f'    up: {{ mode: "Axis"; axis: "REL_WHEEL"; axis_multiplier: {speed:.1f}; }};',
            f'    down: {{ mode: "Axis"; axis: "REL_WHEEL"; axis_multiplier: {-speed:.1f}; }};',
            "};"]


def _indent(lines, spaces):
    return ["" if not line else " " * spaces + line for line in lines]


def to_logid_cfg(settings):
    """Render the settings as libconfig text for /etc/logid.cfg."""
    devices = []
    for name, device in settings["devices"].items():
        body = []
        if "scroll_speed" in device or "scroll_invert" in device:
            body += _scroll_entry(scroll_speed(device), scroll_inverted(device))
        buttons = []
        for cid, _ in visible_controls(device):
            entry = _button_entry(get_button(device, cid))
            if entry:
                buttons.append("\n".join([
                    "{", f"    // {control_name(cid)}", f"    cid: {cid:#04x};", *_indent(entry, 4), "}"]))
        if buttons:
            body += ["buttons: (", *_indent(",\n".join(buttons).split("\n"), 4), ");"]
        if body:
            devices.append("\n".join(["{", f"    name: {_quote(name)};", *_indent(body, 4), "}"]))
    for name in settings.get("scroll_restore", []):
        if name not in settings["devices"]:
            devices.append("\n".join(["{", f"    name: {_quote(name)};", *_indent(_scroll_entry(1), 4), "}"]))

    out = [GENERATED_HEADER + " Changes made here by hand are replaced the next time you press Apply.", ""]
    if devices:
        out += ["devices: (", *_indent(",\n".join(devices).split("\n"), 0), ");", ""]
    else:
        out += ["devices: ( );", ""]
    return "\n".join(out)


def installed_cfg():
    try:
        return LOGID_CFG.read_text()
    except OSError:
        return None


def is_applied(settings):
    """True when /etc/logid.cfg already matches the settings, ignoring layout."""
    def lines(text):
        return [line.strip() for line in (text or "").splitlines()[1:] if line.strip()]
    installed = installed_cfg()
    return installed is not None and lines(to_logid_cfg(settings)) == lines(installed)


def has_handwritten_cfg():
    """True when /etc/logid.cfg has real settings that this app didn't write."""
    text = installed_cfg()
    if not text or text.startswith(GENERATED_HEADERS):
        return False
    stripped = re.sub(r"//.*|#.*|/\*.*?\*/", "", text, flags=re.DOTALL)
    return bool(stripped.strip())
